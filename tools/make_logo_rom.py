"""Generate the Logo pattern ROM from the project logo.

Pipeline: assets/logo.svg is rasterized with librsvg at 2x (headless
Chrome mis-renders this file - it paints part of the traced VFD group
over the letters; librsvg matches the design reference), then this
script resamples it to 636x188 field pixels (fills the CRT-safe area at
correct 4:3 aspect given the core's tall 724x240-per-field pixels),
quantizes to a 16-color adaptive palette (no dither - flat art, and
dither sparkle would read as chroma noise after NTSC encoding), and emits:

  rtl/logo_rom.mem      - one hex nibble per pixel, 640-px row stride
                          (4 waste px/row buys shift-add addressing)
  rtl/logo_palette.svh  - the 16-entry palette as a Verilog case body

Usage (system python has the gi/Rsvg bindings):
  /usr/bin/python3 -c "
  import gi, cairo; gi.require_version('Rsvg', '2.0')
  from gi.repository import Rsvg
  h = Rsvg.Handle.new_from_file('assets/logo.svg')
  surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, 1200, 840)
  vp = Rsvg.Rectangle(); vp.x = vp.y = 0; vp.width = 1200; vp.height = 840
  h.render_document(cairo.Context(surf), vp)
  surf.write_to_png('/tmp/logo_render.png')"
  python3 tools/make_logo_rom.py /tmp/logo_render.png
"""

import sys
from PIL import Image

W, H, STRIDE = 636, 188, 640

src = Image.open(sys.argv[1]).convert("RGB")
img = src.resize((W, H), Image.LANCZOS)

# Greedy diverse palette: pin the art's background color (entry 0 - the
# FPGA paints the off-window surround with it, so it must survive
# exactly), then add the most frequent colors that are at least DIST
# apart. Keeps small-but-distinct clusters (the VFD greens) that
# frequency-blind quantizers merge away.
import numpy as np

BG = (0x2A, 0x2A, 0x2A)
DIST = 28

arr = np.asarray(img, dtype=np.int32)
colors, counts = np.unique(arr.reshape(-1, 3), axis=0, return_counts=True)
order = np.argsort(-counts)

palette_rgb = [BG]
for i in order:
    c = tuple(int(v) for v in colors[i])
    if all(sum((a - b) ** 2 for a, b in zip(c, p)) >= DIST * DIST for p in palette_rgb):
        palette_rgb.append(c)
    if len(palette_rgb) == 16:
        break
while len(palette_rgb) < 16:
    palette_rgb.append((0, 0, 0))

pal = np.array(palette_rgb, dtype=np.int32)
dists = ((arr[:, :, None, :] - pal[None, None, :, :]) ** 2).sum(axis=3)
index_map = dists.argmin(axis=2).astype(np.uint8)

palette = [v for c in palette_rgb for v in c]
pal_img = Image.fromarray(index_map, mode="P")
pal_img.putpalette(palette + [0] * (768 - len(palette)))
pixels = pal_img.load()

with open("rtl/logo_rom.mem", "w") as f:
    for y in range(H):
        for x in range(STRIDE):
            idx = pixels[min(x, W - 1), y] if x < W else 0
            f.write(f"{idx:x}\n")

with open("rtl/logo_palette.svh", "w") as f:
    f.write("// SPDX-License-Identifier: GPL-2.0-or-later\n")
    f.write("// Generated by tools/make_logo_rom.py - do not edit\n")
    for i in range(16):
        r, g, b = palette[i * 3 : i * 3 + 3]
        f.write(f"\t4'd{i}: {{r, g, b}} <= 24'h{r:02X}{g:02X}{b:02X};\n")

print("palette:", [f"#{palette[i*3]:02X}{palette[i*3+1]:02X}{palette[i*3+2]:02X}" for i in range(16)])

# preview: palette-quantized image blown up for eyeballing
pal_img.convert("RGB").resize((W, H * 2), Image.NEAREST).save("/tmp/logo_rom_preview.png")
print(f"wrote rtl/logo_rom.mem ({STRIDE*H} nibbles), rtl/logo_palette.svh, /tmp/logo_rom_preview.png")
